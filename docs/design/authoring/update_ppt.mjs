// Replace only the relevant passages, retaining each original shape and position.
function edit(page, replacements) {
  const slide = slides[page - 1];
  for (const [before, after] of replacements) {
    const matches = slide.shapes.items.filter(shape => String(shape.text).includes(before));
    if (matches.length !== 1) throw new Error(`Slide ${page}: ${matches.length} matches for ${before}`);
    const shape = matches[0];
    // This path keeps inherited styling and layout, including multiline paragraph formats.
    shape.text.replace(before, after);
    if (!String(shape.text).includes(after)) throw new Error(`Slide ${page}: replacement failed for ${before}`);
  }
}

function notes(page, value) {
  slides[page - 1].speakerNotes.text = value;
}

